// Prebuild the player's close-range vehicles.
//
// The shape generator runs offline so the game never spends a frame lofting a car, and the
// result is a dynamic import rather than part of the bundle, so nobody who only looks at the
// city pays for it. Dimensions and anchors ride along because neither survives a scene graph
// round trip in a form the runtime can trust: the anchors become node positions the wheels
// then move, so their rest values have to be recorded separately.
import {mkdirSync,writeFileSync,readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {BufferGeometry} from 'three';
import {mergeVertices} from 'three/addons/utils/BufferGeometryUtils.js';
import {createVehicleAsset} from '../src/player/vehicle-asset.mjs';
import {VEHICLES} from '../src/traffic/config.mjs';

const models={},dimensions={},anchors={};
let triangles=0;
// Two-wheelers are built at runtime (traffic/motorbike-shape.mjs), not lofted here.
for(const type of Object.keys(VEHICLES).filter(t=>t!=='scooter'&&!VEHICLES[t].twoWheel)){
 const asset=createVehicleAsset(type);
 asset.root.traverse(o=>{
  if(!o.isMesh)return;
  const old=o.geometry;
  const copy=new BufferGeometry().copy(old);
  delete copy.parameters;
  o.geometry=mergeVertices(copy,1e-5);
  copy.dispose();old.dispose();
 });
 models[type]=asset.root.toJSON();
 dimensions[type]=asset.dimensions;
 anchors[type]=asset.anchorPoints;
 triangles+=asset.triangles;
 asset.dispose();
}
// Stable identifiers make rebuilding reviewable and reproducible.
let json=JSON.stringify({version:2,models,dimensions,anchors},
 (key,value)=>typeof value==='number'?Math.round(value*10000)/10000:value);
const ids=new Map();
json=json.replace(/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/gi,
 id=>{if(!ids.has(id))ids.set(id,`playable-${ids.size}`);return ids.get(id);});
const key=createHash('sha256')
 .update(readFileSync('src/traffic/vehicle-shape.mjs'))
 .update(readFileSync('src/player/vehicle-asset.mjs'))
 .update(readFileSync('src/traffic/config.mjs')).digest('hex');
const pack=JSON.parse(json);pack.sourceKey=key;
mkdirSync('src/player/generated',{recursive:true});
writeFileSync('src/player/generated/vehicles.mjs',
 '// Generated by npm run bake:playable.\nexport default JSON.parse('+JSON.stringify(JSON.stringify(pack))+');\n');
console.log(`Prebuilt ${Object.keys(models).length} vehicles, ${triangles} triangles, `+
 `${Buffer.byteLength(JSON.stringify(pack))} bytes`);
